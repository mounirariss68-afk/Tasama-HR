/**
 * The staging area for a client being taken on (design/payroll-addendum.md §13, §19): the dropped
 * files and what each lane read from them, in tasama.onboarding. Nothing here touches a client master.
 */
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import JSZip from 'jszip';
import { pool } from '../db.js';
import { today } from '../clock.js';
import { kindOf } from './read.js';
import { LANES, readClient, type Lane, type Issue } from './lanes.js';

const here = dirname(fileURLToPath(import.meta.url));
/** The folder the presenter drops in D10, as generated by tools/new-client/make.ts. */
export const DEMO_FOLDER = resolve(here, '../../../../demo-files/soudah');
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

export async function create(by: string) {
  const r = await pool.query(`INSERT INTO tasama.onboarding (created_by, lanes) VALUES ($1, $2) RETURNING id`, [by, JSON.stringify(blankLanes())]);
  return r.rows[0].id as number;
}
const blankLanes = () => LANES.map((l): Lane => ({ key: l.key, state: 'WAITING', files: 0, headline: '', stats: [], issues: 0 }));

export async function addFile(id: number, path: string, content: Buffer) {
  const clean = path.replace(/\\/g, '/').replace(/^\/+/, '');
  await pool.query(`INSERT INTO tasama.onboarding_files (onboarding_id, path, size, kind, content) VALUES ($1,$2,$3,$4,$5)
    ON CONFLICT (onboarding_id, path) DO UPDATE SET size=EXCLUDED.size, kind=EXCLUDED.kind, content=EXCLUDED.content, added_at=now()`, [id, clean, content.length, kindOf(clean), content]);
}

const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
/** The demo folder, as if the presenter had dragged it. */
export async function addDemoFiles(id: number) {
  if (!existsSync(DEMO_FOLDER)) throw new Error('The demo folder is missing. Run npm run make:soudah.');
  const files = walk(DEMO_FOLDER);
  for (const f of files) await addFile(id, relative(DEMO_FOLDER, f), readFileSync(f));
  return files.length;
}
/** The demo folder as one zip, for Demo control › Demo files. */
export async function demoZip() {
  const zip = new JSZip();
  for (const f of walk(DEMO_FOLDER)) zip.file(`Soudah Development/${relative(DEMO_FOLDER, f)}`, readFileSync(f));
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

const running = new Map<number, Promise<void>>();
/** Reads the files into the lanes, one lane after another, `pace` milliseconds apart so the screen can show them fill. */
export function read(id: number, pace = 0, columnMap?: Record<string, string>) {
  if (running.has(id)) return running.get(id)!;
  const job = (async () => {
    const files = (await pool.query(`SELECT path, content FROM tasama.onboarding_files WHERE onboarding_id=$1 ORDER BY path`, [id])).rows as { path: string; content: Buffer }[];
    const lanes = blankLanes();
    lanes[0].state = 'READING';
    const save = (extra = '', params: unknown[] = []) => pool.query(`UPDATE tasama.onboarding SET lanes=$2${extra} WHERE id=$1`, [id, JSON.stringify(lanes), ...params]);
    await pool.query(`UPDATE tasama.onboarding SET state='READING', issues='[]', staged='{}', column_map=$2 WHERE id=$1`, [id, JSON.stringify(columnMap ?? {})]);
    await save();
    const all: Issue[] = [];
    try {
      const out = await readClient(files, {
        today: today(), columnMap,
        onLane: async (lane, issues) => {
          if (pace) await sleep(pace);
          const i = lanes.findIndex((l) => l.key === lane.key);
          lanes[i] = lane;
          if (lanes[i + 1]) lanes[i + 1].state = 'READING';
          all.push(...issues);
          await save(`, issues=$3`, [JSON.stringify(all)]);
        },
      });
      await pool.query(`UPDATE tasama.onboarding SET state='STAGED', client_key=$2, name=$3, lanes=$4, issues=$5, staged=$6, read_at=now() WHERE id=$1`,
        [id, out.staged.client.key, out.staged.client.name, JSON.stringify(out.lanes), JSON.stringify(out.issues), JSON.stringify(out.staged)]);
    } catch (e: any) {
      console.error('[onboarding]', e);
      await pool.query(`UPDATE tasama.onboarding SET state='DRAFT', lanes=$2 WHERE id=$1`, [id, JSON.stringify(lanes.map((l) => (l.state === 'READING' ? { ...l, state: 'EMPTY', headline: `Could not be read: ${e?.message ?? e}` } : l)))]);
    } finally {
      running.delete(id);
    }
  })();
  running.set(id, job);
  return job;
}

/** What the screen shows: the lanes, the issues and the files, without the staged rows. */
export async function get(id: number) {
  const o = (await pool.query(`SELECT id, client_key, name, state, lanes, issues, column_map, request_ref, created_at, read_at, live_at,
      staged->'client' AS client, (SELECT COUNT(*)::int FROM jsonb_array_elements(COALESCE(staged->'roster','[]')) x WHERE x->>'held' IS NULL) AS ready, staged->'columnMap' AS columns, staged->'history'->'months' AS months, staged->'provisions' AS provisions
    FROM tasama.onboarding WHERE id=$1`, [id])).rows[0];
  if (!o) return null;
  const files = (await pool.query(`SELECT kind, COUNT(*)::int n, SUM(size)::int bytes FROM tasama.onboarding_files WHERE onboarding_id=$1 GROUP BY kind`, [id])).rows;
  const issues = o.issues as Issue[];
  return { ...o, files, counts: { issues: issues.length, client: issues.filter((i) => i.who === 'CLIENT').length } };
}
export const latest = async () => (await pool.query(`SELECT id FROM tasama.onboarding WHERE state <> 'LIVE' ORDER BY id DESC LIMIT 1`)).rows[0]?.id as number | undefined;
export const remove = (id: number) => pool.query(`DELETE FROM tasama.onboarding WHERE id=$1 AND state <> 'LIVE'`, [id]);
