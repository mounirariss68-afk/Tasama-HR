/** Month names as the platform writes them in English ("25 Oct", "October 2026"). */
const MONTHS: Record<string, string> = { jan: 'يناير', feb: 'فبراير', mar: 'مارس', apr: 'أبريل', may: 'مايو', jun: 'يونيو', jul: 'يوليو', aug: 'أغسطس', sep: 'سبتمبر', oct: 'أكتوبر', nov: 'نوفمبر', dec: 'ديسمبر' };
const monthAr = (w: string) => MONTHS[w.slice(0, 3).toLowerCase()] ?? w;
const dayAr = (d: string) => d.replace(/(\d{1,2}) ([A-Za-z]{3,9})(?: (\d{4}))?/, (_m, n, m, y) => `${n} ${monthAr(m)}${y ? ` ${y}` : ''}`);
const days = (n: number) => (n === 1 ? 'يوم واحد' : n === 2 ? 'يومان' : n <= 10 ? `${n} أيام` : `${n} يومًا`);
const months = (n: number) => (n === 1 ? 'شهر واحد' : n === 2 ? 'شهران' : n <= 10 ? `${n} أشهر` : `${n} شهرًا`);
const DATE = '(\\d{1,2} [A-Za-z]{3,9}(?: \\d{4})?)';

